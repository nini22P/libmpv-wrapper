use std::env;
use std::path::PathBuf;

fn main() {
    #[cfg(target_os = "linux")]
    println!("cargo:rustc-link-arg=-Wl,-rpath,$ORIGIN");

    #[cfg(target_os = "macos")]
    println!("cargo:rustc-link-arg=-Wl,-rpath,@loader_path");

    println!("cargo:rerun-if-changed=src/ffi.rs");

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());

    cbindgen::Builder::new()
        .with_crate(manifest_dir)
        .with_language(cbindgen::Language::C)
        .with_include_guard("LIBMPV_WRAPPER_H")
        .with_header("/* automatically generated by cbindgen */")
        .generate()
        .expect("Failed to generate C bindings using cbindgen")
        .write_to_file("include/libmpv_wrapper.h");

    bindgen::Builder::default()
        .header("include/libmpv_wrapper.h")
        .formatter(bindgen::Formatter::Prettyplease)
        .dynamic_library_name("LibmpvWrapper")
        .allowlist_function("mpv_wrapper_.*")
        .allowlist_type("MpvHandle")
        .allowlist_type("EventCallback")
        .impl_debug(true)
        .generate()
        .expect("Unable to generate bindings")
        .write_to_file("include/libmpv_wrapper_bindings.rs")
        .expect("Unable to write bindings");
}
